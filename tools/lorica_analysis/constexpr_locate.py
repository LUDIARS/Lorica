"""constexpr locator: which functions to try and where the specifier goes. @implements SPEC-LR-ANALYZE

The locator never decides whether a function can be constexpr; the compiler does
(constexpr_trial). From an extracted file it states facts only:
  - functions already constexpr or consteval (counted, never tried);
  - exclusions, never tried: lambdas bound to a variable, functions generated by a
    macro invocation, main, a reasoned `ignore(constexpr)` suppression, and
    definitions in a source file with external linkage (constexpr implies inline:
    the definition would have to move to a header, which changes linkage and the
    exported symbols);
  - the insertion point: after the template head, requires-clause and attributes,
    before the first decl-specifier. Every insertion is checked by extracting the
    mutated text again: the function must gain `constexpr` and nothing else may
    change, otherwise the function is refused (an unparsed region), never guessed;
  - hidden by default: templates (and members of class templates), and members of
    a class that declares constructors none of which is constexpr or defaulted.
    Every compiler accepts the specifier on these, so only a witness says anything.
"""
from typing import Dict, List, NamedTuple, Optional, Tuple

from .extract import Function, Region, SourceFile, analyse_text
from .gate import suppressions
from .lexer import IDENTIFIER, KEYWORD, PUNCT, Token

EXTERNAL = ("defined in a source file with external linkage: constexpr implies inline, so the "
            "definition would have to move to a header, which changes linkage and exported symbols")
TEMPLATE = "template"
MEMBER = "member of a class without a constexpr constructor"
_ACCESS = frozenset(("public", "private", "protected"))
_ATTRIBUTES = frozenset(("alignas", "__attribute__", "__attribute", "__declspec", "_Pragma"))


class Candidate(NamedTuple):
    function: Function
    offset: int         # text offset where "constexpr " is inserted
    hidden: str         # TEMPLATE, MEMBER or ""


class Located(NamedTuple):
    candidates: List[Candidate]
    excluded: List[Tuple[Function, str]]   # (function, reason)
    already: int                           # already constexpr or consteval
    refused: List[Region]                  # no verified insertion point


def probe(number: int) -> str:
    """A canary the compiler prints when, and only when, it reads this text."""
    return '_Pragma("message(\\"lorica-probe:%d\\")") ' % number


def render(text: str, insertions: List[Tuple[int, str]]) -> str:
    """text with each (offset, string) inserted; equal offsets keep their order."""
    pieces, last = [], 0
    for offset, string in sorted(insertions, key=lambda item: item[0]):
        pieces += [text[last:offset], string]
        last = offset
    return "".join(pieces) + text[last:]


def _line_starts(text: str) -> List[int]:
    starts = [0]
    for index, char in enumerate(text):
        if char == "\n":
            starts.append(index + 1)
    return starts


def _offset(text: str, starts: List[int], token: Token) -> Optional[int]:
    offset = starts[token.line - 1] + token.column - 1 if token.line <= len(starts) else -1
    return offset if offset >= 0 and text.startswith(token.text, offset) else None


def excluded(source: SourceFile, function: Function) -> str:
    if function.kind == "lambda":
        return "a lambda bound to a variable: implicitly constexpr since C++17 where it qualifies"
    if function.kind == "macro-function":
        return "generated by a macro invocation"
    if function.name.split("::")[-1] == "main" and not function.in_class_body:
        return "main cannot be constexpr"
    reason = suppressions(source, function).get("constexpr")
    if reason:
        return "suppressed: " + reason
    if not (function.in_header or function.in_class_body or function.in_unnamed_namespace
            or function.specifiers & {"static", "inline"}):
        return EXTERNAL
    return ""


def _head(tokens: List[Token], match: List[int], k: int, first_line: int = 0) -> int:
    """First token of the declaration whose head ends before token k."""
    while k > 0:
        token = tokens[k - 1]
        if token.line < first_line:
            break
        if token.kind == PUNCT:
            opener = match[k - 1]
            if token.text in (")", "]", "}") and 0 <= opener < k - 1:
                if token.text == "}" and (not first_line or tokens[opener].line < first_line):
                    break
                k = opener
                continue
            if token.text in (";", "{", "}"):
                break
            if token.text == ":" and k >= 2 and tokens[k - 2].text in _ACCESS:
                break
        k -= 1
    return k


def _angle_end(tokens: List[Token], match: List[int], k: int, end: int) -> Optional[int]:
    """Index after the `>` closing the `<` at k."""
    depth = 0
    while k < end:
        token = tokens[k]
        if token.kind == PUNCT and token.text in "([{" and match[k] > k:
            k = match[k] + 1
            continue
        if token.text == "<":
            depth += 1
        elif token.text in (">", ">>"):
            depth -= len(token.text)
            if depth <= 0:
                return k + 1
        k += 1
    return None


def _constraint_end(tokens: List[Token], match: List[int], k: int, end: int) -> Optional[int]:
    """Index after a requires-clause's constraint expression starting at k."""
    while k < end:
        if tokens[k].text == "(" and match[k] > k:
            k = match[k] + 1
        elif tokens[k].text == "requires":
            k += 1
            for opener in ("(", "{"):
                if k < end and tokens[k].text == opener and match[k] > k:
                    k = match[k] + 1
        elif tokens[k].text in ("true", "false"):
            k += 1
        else:
            start = k
            while k is not None and k < end:
                token = tokens[k]
                if token.text == "::" or (token.kind == IDENTIFIER and (k == start or tokens[k - 1].text == "::")):
                    k += 1
                elif token.text == "<" and k > start:
                    k = _angle_end(tokens, match, k, end)
                else:
                    break
            if k is None or k == start:
                return None
        if k < end and tokens[k].text in ("&&", "||"):
            k += 1
            continue
        return k
    return None


def _decl_specifiers(tokens: List[Token], match: List[int], k: int, end: int) -> Optional[int]:
    """Skip the template head, requires-clause and attributes from k."""
    while k is not None and k < end:
        token, following = tokens[k], tokens[k + 1] if k + 1 < end else None
        if following is None:
            return k
        if token.text == "template" and following.text == "<":
            k = _angle_end(tokens, match, k + 1, end)
        elif token.text == "requires":
            k = _constraint_end(tokens, match, k + 1, end)
        elif token.text == "[" and following.text == "[" and match[k] > k:
            k = match[k] + 1
        elif token.text in _ATTRIBUTES and following.text == "(" and match[k + 1] > k:
            k = match[k + 1] + 1
        else:
            return k
    return None


def _parents(tokens: List[Token], match: List[int]) -> Dict[int, int]:
    """{index of a `{`: index of the enclosing `{` or -1}."""
    parents, stack = {}, []
    for k, token in enumerate(tokens):
        if token.kind != PUNCT or match[k] < 0:
            continue
        if token.text == "{":
            parents[k] = stack[-1] if stack else -1
            stack.append(k)
        elif token.text == "}" and stack and stack[-1] == match[k]:
            stack.pop()
    return parents


def _class_head(tokens: List[Token], match: List[int], brace: int) -> Optional[List[str]]:
    """Head texts of the brace at index brace when it opens a class, else None."""
    texts = [t.text for t in tokens[_head(tokens, match, brace):brace]]
    keys = [k for k, text in enumerate(texts) if text in ("class", "struct", "union")
            and (k == 0 or texts[k - 1] != "enum")]
    return texts if keys and "namespace" not in texts else None


def _class_by_name(tokens: List[Token], match: List[int], name: str) -> Optional[int]:
    """Index of the body `{` of the class `name` defined in this file."""
    for k in range(len(tokens) - 1):
        if tokens[k].kind == KEYWORD and tokens[k].text in ("class", "struct", "union") \
                and tokens[k + 1].text == name:
            j = k + 2
            while j < len(tokens) and tokens[j].text not in ("{", ";"):
                j = match[j] + 1 if tokens[j].text in ("(", "[") and match[j] > j else j + 1
            if j < len(tokens) and tokens[j].text == "{" and match[j] > j:
                return j
    return None


def _constructors(tokens: List[Token], match: List[int], brace: int, name: str) -> List[bool]:
    """For each constructor declared in the class body: constexpr, consteval or defaulted."""
    found, k, start, close = [], brace + 1, brace + 1, match[brace]
    while k < close:
        token = tokens[k]
        if token.kind == PUNCT and token.text in "([{" and match[k] > k:
            if token.text == "(" and k - 1 >= start and tokens[k - 1].text == name \
                    and tokens[k - 2].text not in ("~", "::", ".", "->", "operator"):
                head = {t.text for t in tokens[start:k - 1]}
                after = match[k] + 1
                if not head & {"=", "friend", "return"}:
                    found.append(bool(head & {"constexpr", "consteval"}) or (
                        after + 1 < close and tokens[after].text == "=" and tokens[after + 1].text == "default"))
            k = match[k] + 1
            if token.text == "{":
                start = k
            continue
        if token.text == ";" or (token.text == ":" and tokens[k - 1].text in _ACCESS):
            start = k + 1
        k += 1
    return found


def _hidden(source: SourceFile, parents: Dict[int, int], function: Function) -> str:
    tokens, match = source.tokens, source.match
    if "template" in function.specifiers:
        return TEMPLATE
    parts = function.name.split("::")
    classes = []    # (brace, head texts), innermost first
    if function.in_class_body:
        brace = parents.get(function.body[0], -1)
        while brace >= 0:
            head = _class_head(tokens, match, brace)
            if head is not None:
                classes.append((brace, head))
            brace = parents.get(brace, -1)
    elif len(parts) > 1:
        brace = _class_by_name(tokens, match, parts[-2])
        if brace is not None:
            classes.append((brace, _class_head(tokens, match, brace) or []))
    if any("template" in head for _, head in classes):
        return TEMPLATE
    if not classes or function.kind in ("constructor", "destructor") or \
            function.specifiers & {"static", "friend"}:
        return ""
    constructors = _constructors(tokens, match, classes[0][0], parts[-2])
    return MEMBER if constructors and not any(constructors) else ""


def declaration_offset(source: SourceFile, text: str, line: int, name: str) -> Optional[int]:
    """Insertion offset of the declaration of `name` (qualified) whose name is on `line`."""
    tokens, match = source.tokens, source.match
    short = name.split("::")[-1]
    destructor = short.startswith("~")
    hits = [k for k, t in enumerate(tokens) if t.line == line and t.text == short.lstrip("~")
            and (not destructor or (k and tokens[k - 1].text == "~"))]
    if len(hits) != 1 or short.startswith("operator"):
        return None
    k = hits[0] - (1 if destructor else 0)
    start = _decl_specifiers(tokens, match, _head(tokens, match, k), k)
    return None if start is None else _offset(text, _line_starts(text), tokens[start])


def locate(source: SourceFile, text: str) -> Located:
    tokens, match = source.tokens, source.match
    starts, parents = _line_starts(text), _parents(tokens, match)
    candidates, excluded_, refused, already = [], [], [], 0
    for function in source.functions:
        if function.specifiers & {"constexpr", "consteval"}:
            already += 1
            continue
        reason = excluded(source, function)
        if reason:
            excluded_.append((function, reason))
            continue
        open_ = function.body[0]
        start = _decl_specifiers(tokens, match, _head(tokens, match, open_, function.start_line), open_)
        offset = None if start is None else _offset(text, starts, tokens[start])
        if offset is None:
            refused.append(Region(function.file, function.start_line, function.line,
                                  "constexpr: no insertion point found"))
        else:
            candidates.append(Candidate(function, offset, _hidden(source, parents, function)))
    candidates, more = _checked(source, text, candidates)
    return Located(candidates, excluded_, already, refused + more)


def _checked(source: SourceFile, text: str, candidates: List[Candidate]):
    """Keep the candidates whose insertion the extractor reads back as intended."""
    if not candidates:
        return candidates, []
    mutated = analyse_text(source.path, render(text, [(c.offset, probe(0) + "constexpr ")
                                                      for c in candidates]))
    before = {(f.line, f.name): f.specifiers for f in source.functions}
    after = {(f.line, f.name): f.specifiers for f in mutated.functions}
    tried = {(c.function.line, c.function.name) for c in candidates}
    if before.keys() != after.keys() or any(after[k] != before[k] for k in before if k not in tried):
        return [], [Region(c.function.file, c.function.start_line, c.function.line,
                           "constexpr: inserting the specifier changed another declaration")
                    for c in candidates]
    kept = [c for c in candidates if after[(c.function.line, c.function.name)]
            == before[(c.function.line, c.function.name)] | {"constexpr"}]
    return kept, [Region(c.function.file, c.function.start_line, c.function.line,
                         "constexpr: the specifier is not read back at the insertion point")
                  for c in candidates if c not in kept]
