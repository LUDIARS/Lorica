"""The constexpr subcommand: locate, try with the compiler, report, gate. @implements SPEC-LR-ANALYZE

Three result states per compiler and standard: rejected, accepted (necessary
condition only) and witnessed (a user witness that constant-evaluates the
function compiled; the only state that verifies anything). Without --compiler and
without --compile-commands nothing is compiled and only the locator's facts are
listed. Results are gate entries with the metrics `witnessed` and `accepted` (the
number of configurations in that state), so thresholds, the baseline, suppressions
and exit codes work as for complexity, and a run fails only when asked.
"""
import difflib
import json
import os
import sys
from typing import Dict, List, Tuple

from . import constexpr_compiler as compiler, gate, report, sources
from .constexpr_compiler import RANK, ToolError
from .constexpr_locate import EXTERNAL, locate, render
from .constexpr_overlay import Overlay
from .constexpr_trial import ACCEPTED, INACTIVE, REJECTED, WITNESSED, Configuration, Trial, run_trial
from .extract import HEADER_EXTENSIONS, Region, analyse_text

METRICS = ("witnessed", "accepted")
HELP = "try constexpr with GCC or Clang; only a witness verifies (needs a compiler to try anything)"
_CATEGORIES = (("suppressed", "suppressed by a reasoned ignore(constexpr) comment"),
               ("defined in a source", EXTERNAL), ("a lambda", "lambdas bound to a variable"),
               ("generated by a macro", "generated by a macro invocation"), ("main", "main"))


def add_options(parser) -> None:
    parser.add_argument("--compiler", action="append", default=[], metavar="CXX",
                        help="GCC or Clang to try (repeatable); replaces the database's compiler; without "
                             "--compile-commands each selected source file is compiled alone")
    parser.add_argument("--std", action="append", default=[], choices=sorted(RANK, key=RANK.get)[3:],
                        metavar="N", help="standard to try (repeatable: 17, 20, 23); default: each unit's own")
    parser.add_argument("--witnesses", metavar="FILE", help="JSON {schema_version: 1, witnesses: {key: code}}")
    parser.add_argument("--root", metavar="DIR", help="tree to copy (default: the analysed files' tree)")
    parser.add_argument("--show-hidden", action="store_true", help="list templates and members of non-literal classes")
    parser.add_argument("--emit-patch", metavar="FILE", help="write a unified diff of the results witnessed everywhere")
    parser.add_argument("--timeout", type=float, default=120.0, metavar="SECONDS", help="per compile (default 120)")
    parser.add_argument("--jobs", type=int, default=1, metavar="N", help="parallel compiles (default 1)")


def _witnesses(path: str) -> Dict[str, str]:
    try:
        with open(path, encoding="utf-8") as stream:
            data = json.load(stream)
        if data.get("schema_version") != 1:
            raise ValueError("schema_version %r is not 1" % data.get("schema_version"))
        found = {k: "\n".join(v) if isinstance(v, list) else v for k, v in data["witnesses"].items()}
        if not all(isinstance(v, str) for v in found.values()):
            raise ValueError("a witness must be a string or a list of lines")
        return found
    except (OSError, ValueError, KeyError, TypeError, AttributeError) as error:
        raise sources.InputError("%s: not a usable witness file (%s)" % (path, error))


def _root(args, files: List[str], units: List[compiler.Unit]) -> str:
    if args.root:
        return os.path.realpath(args.root)
    homes = [os.path.dirname(os.path.realpath(f)) for f in files]
    tops = {d for u in units for d in map(os.path.realpath, compiler.include_directories(u))
            if any(h == d or h.startswith(d.rstrip(os.sep) + os.sep) for h in homes)}
    return os.path.commonpath(homes + sorted(tops))


def _configurations(args, units: List[compiler.Unit], toolchains) -> List[Configuration]:
    groups: Dict[Tuple[str, str], List[compiler.Unit]] = {}
    skipped: Dict[Tuple[str, str], int] = {}
    for unit in units:
        for command in args.compiler or [unit.compiler]:
            toolchain = toolchains[command]
            own = unit.std or toolchain.default_std
            for std in args.std or [own]:
                key = (command, std)
                if RANK[own] > RANK[std]:
                    skipped[key] = skipped.get(key, 0) + 1
                else:
                    groups.setdefault(key, []).append(unit)
    keys = sorted(set(groups) | set(skipped), key=lambda k: (k[0], RANK[k[1]]))
    return [Configuration(toolchains[c], s, groups.get((c, s), []), skipped.get((c, s), 0)) for c, s in keys]


def _patch(path: str, files, trials: List[Trial], order, root: str) -> int:
    """Write the diff of the candidates witnessed in every configuration; returns their number."""
    everywhere = [i for i in range(len(order)) if trials and all(
        t.results.get(i, (None,))[0] == WITNESSED for t in trials)]
    inserts: Dict[str, List[Tuple[int, str]]] = {}
    for i in everywhere:
        file, candidate = order[i]
        inserts.setdefault(file, []).append((candidate.offset, "constexpr "))
        for fixed, offset in {f for t in trials for f in t.fixups.get(i, ())}:
            inserts.setdefault(fixed, []).append((offset, "constexpr "))
    out = []
    for file in sorted(inserts):
        text = files[file][1]
        name = os.path.relpath(os.path.realpath(file), root).replace(os.sep, "/")
        out += difflib.unified_diff(text.splitlines(True), render(text, inserts[file]).splitlines(True),
                                    "a/" + name, "b/" + name)
    with open(path, "w", encoding="utf-8", newline="") as stream:
        stream.write("".join(out))
    return len(everywhere)


def _labels(configurations: List[Configuration]) -> str:
    """"g++ c++17, c++20; clang++ c++23"."""
    by_compiler: Dict[str, List[str]] = {}
    for c in configurations:
        by_compiler.setdefault(os.path.basename(c.toolchain.command), []).append("c++" + c.std)
    return "; ".join("%s %s" % (name, ", ".join(stds)) for name, stds in by_compiler.items())


def _states(trials: List[Trial], i: int) -> List[str]:
    groups: Dict[Tuple[str, str], List[Configuration]] = {}
    for t in trials:
        groups.setdefault(tuple(t.results[i]), []).append(t.configuration)
    return ["    %s %s: %s" % (s, _labels(c), d) for (s, d), c in groups.items()]


def verdict(states) -> str:
    if states == {WITNESSED}:
        return "witnessed everywhere"
    if WITNESSED in states:
        return "witnessed on some configurations only"
    if ACCEPTED in states:
        return "accepted at most (not verified)"
    return {frozenset((REJECTED,)): "rejected everywhere", frozenset((INACTIVE,)): "inactive in every configuration"
            }.get(frozenset(states), "not decided")


def _text(args, located, order, trials, why_not: str, keys: List[str], unused: List[str]) -> List[str]:
    candidates = [c for _, c in order]
    excluded = [(f, r) for loc in located.values() for f, r in loc.excluded]
    compiled = not why_not
    out = ["functions not declared constexpr: %d (tried %d, excluded %d); already constexpr %d; "
           "variables are not analysed" % (len(candidates) + len(excluded), len(candidates) if compiled else 0,
                                           len(excluded), sum(loc.already for loc in located.values()))]
    if why_not:
        out.append("nothing was compiled (%s): no function is reported as rejected, accepted or witnessed"
                   % why_not)
        out.append("not tried: %d%s" % (len(candidates), " (--all lists them)" if candidates and not args.all else ""))
        if args.all:
            out += ["    not tried %s:%d %s%s" % (c.function.file, c.function.line, c.function.name,
                                                  " (hidden: %s)" % c.hidden if c.hidden else "") for c in candidates]
    for t in trials:
        c = t.configuration
        out.append("tried %s -std=c++%s: units %d%s; strict flags %s%s" % (
            c.toolchain.label, c.std, len(c.units), ", %d skipped (configured for a newer standard)" % c.skipped
            if c.skipped else "", " ".join(compiler.STRICT), "; removed " + " ".join(t.removed) if t.removed else ""))
        if args.all and t.command:
            out.append("    command: " + " ".join(t.command))
    hidden = {}
    for i, c in enumerate(candidates if compiled else []):
        states = {t.results[i].state for t in trials}
        if c.hidden and WITNESSED not in states and not args.show_hidden:
            hidden[c.hidden] = hidden.get(c.hidden, 0) + 1
            continue
        out.append("%s:%d %s: %s%s" % (c.function.file, c.function.line, c.function.name, verdict(states),
                                       " (hidden: %s)" % c.hidden if c.hidden else ""))
        out += _states(trials, i)
        if ACCEPTED in states and not args.witnesses:
            out.append("    witness key: %s" % keys[i])
    if hidden:
        out.append("hidden: %d (%s); --show-hidden lists them" % (
            sum(hidden.values()), ", ".join("%s %d" % kv for kv in sorted(hidden.items()))))
    if excluded:
        counts = {}
        for _, reason in excluded:
            label = next((text for prefix, text in _CATEGORIES if reason.startswith(prefix)), reason)
            counts[label] = counts.get(label, 0) + 1
        out.append("excluded (not tried): %d%s" % (len(excluded), "" if args.all else " (--all lists them)"))
        out += ["    %d %s" % (n, label) for label, n in counts.items()]
        if args.all:
            out += ["    excluded %s:%d %s: %s" % (f.file, f.line, f.name, r) for f, r in excluded]
    out += ["note: witness not used (no candidate has this key): " + key for key in unused]
    return out


def run(args) -> int:
    if not args.paths and not args.compile_commands:
        print("error: no input: name files or directories, or --compile-commands", file=sys.stderr)
        return 2
    try:
        files = sources.select(args.paths, args.exclude, None if args.paths else args.compile_commands)
        baseline = gate.load_baseline(args.baseline) if args.baseline else None
        witness_file = _witnesses(args.witnesses) if args.witnesses else {}
        units = compiler.database_units(args.compile_commands) if args.compile_commands else []
    except (sources.InputError, ToolError) as error:
        print("error: %s" % error, file=sys.stderr)
        return 2
    units = [u for u in units if not sources._excluded(u.file, args.exclude)]
    if not args.compile_commands and args.compiler:
        units = [compiler.Unit("", os.path.dirname(os.path.abspath(f)), os.path.normpath(os.path.abspath(f)), (
            os.path.abspath(f),), None) for f in files if os.path.splitext(f)[1].lower() not in HEADER_EXTENSIONS]
    compiled = bool(args.compiler or args.compile_commands)
    errors = [] if files else ["no C or C++ file selected"]
    if compiled and not units:
        errors.append("no C++ translation unit to compile")
    located, texts, unparsed, not_analysed, order = {}, {}, [], [], []
    for path in files:
        try:
            text = sources.read(path)
        except sources.InputError as error:
            errors.append(str(error))
            continue
        source = analyse_text(path, text)
        found = locate(source, text)
        if "�" in text and found.candidates:
            found = found._replace(candidates=[], refused=found.refused + [
                Region(path, 1, text.count("\n") + 1, "constexpr: not valid UTF-8, not mutated")])
        key = os.path.normpath(os.path.abspath(path))
        located[key], texts[key] = found, (source, text)
        unparsed += source.unparsed + found.refused
        not_analysed += source.not_analysed
        order += [(key, c) for c in found.candidates]
    entries = [gate.Entry(texts[p][0], c.function, {m: 0 for m in METRICS}) for p, c in order]
    root_dir = os.path.dirname(os.path.abspath(args.witnesses)) if args.witnesses else os.getcwd()
    keys = gate.keys(entries, root_dir)
    witnesses = {keys.index(k): code for k, code in witness_file.items() if k in keys}
    unused = sorted(k for k in witness_file if k not in keys)
    trials: List[Trial] = []
    root = ""
    if compiled and units and order and not errors:
        try:
            toolchains = {c: compiler.detect(c, args.timeout) for c in sorted(set(args.compiler or [u.compiler for u in units]))}
            if not args.compile_commands:
                units = [u._replace(compiler=args.compiler[0]) for u in units]
            root = _root(args, list(texts), units)
            with Overlay(root) as overlay:
                for configuration in _configurations(args, units, toolchains):
                    trial = run_trial(configuration, order, texts, overlay, witnesses, args.jobs, args.timeout)
                    trials.append(trial)
                    errors += trial.errors
        except ToolError as error:
            errors.append(str(error))
            trials = []
    for i, entry in enumerate(entries):
        for metric, state in (("witnessed", WITNESSED), ("accepted", ACCEPTED)):
            entry.metrics[metric] = sum(t.results.get(i, (None,))[0] == state for t in trials)
    if any(t.results.get(i, ("",))[0] == "error" for t in trials for i in range(len(order))) and not errors:
        errors.append("a candidate could not be decided")
    if not trials:      # nothing measured: no metric, so no finding and no baseline value
        entries = [e._replace(metrics={}) for e in entries]
    thresholds = {m: getattr(args, "max_" + m) for m in METRICS if getattr(args, "max_" + m) is not None}
    baseline_root = os.path.dirname(os.path.abspath(args.baseline)) if args.baseline else ""
    findings, improved = gate.evaluate(args.command, entries, thresholds, baseline, baseline_root)
    failed = (thresholds or baseline is not None) and any(not f.suppressed for f in findings)
    incomplete = errors or (args.strict and unparsed)
    result = report.Run(args.command, METRICS, files, entries, unparsed, not_analysed, findings, improved,
                        errors, "incomplete" if incomplete else "fail" if failed else "pass")
    try:
        if args.write_baseline:
            gate.write_baseline(args.write_baseline, args.command, entries)
        if args.emit_patch:
            _patch(args.emit_patch, texts, trials, order, root or os.getcwd())
    except OSError as error:
        print("error: %s: %s" % (error.filename, error.strerror), file=sys.stderr)
        return 2
    why_not = "" if trials else "no --compiler and no --compile-commands" if not compiled else \
        "no candidate" if not order else "see the errors above"
    lines = _text(args, located, order, trials, why_not, keys, unused)
    if args.json:
        data = json.loads(report.to_json(result))
        data["constexpr"] = {
            "compiled": bool(trials), "configurations": [{
                "compiler": t.configuration.toolchain.command, "family": t.configuration.toolchain.family,
                "version": t.configuration.toolchain.version, "std": t.configuration.std,
                "units": len(t.configuration.units), "skipped_units": t.configuration.skipped,
                "strict_flags": list(compiler.STRICT), "removed_flags": t.removed, "command": t.command}
                for t in trials],
            "candidates": [{"key": keys[i], "file": c.function.file, "line": c.function.line,
                            "name": c.function.name, "hidden": c.hidden, "results": [
                                {"configuration": t.configuration.label, "state": t.results[i].state,
                                 "detail": t.results[i].detail} for t in trials]}
                           for i, (_, c) in enumerate(order)],
            "excluded": [{"file": f.file, "line": f.line, "name": f.name, "reason": r}
                         for loc in located.values() for f, r in loc.excluded],
            "already_constexpr": sum(loc.already for loc in located.values()),
            "unused_witnesses": unused}
        sys.stdout.write(json.dumps(data, indent=1) + "\n")
    else:
        text = report.text(result).rstrip("\n").split("\n")
        sys.stdout.write("\n".join(text[:-1] + lines + text[-1:]) + "\n")
    return 2 if incomplete else 1 if failed else 0
